// sayit-paste - deliver text to the focused window. The macOS counterpart of
// the clipboard path in bin/sayit-inject.
//
// Usage:
//   printf '%s' "$TEXT" | sayit-paste     text on stdin, never on the command
//                                         line (argv is visible to every user)
//   sayit-paste --check                   report Accessibility and Secure Input
//
// Environment:
//   INJECT_METHOD  auto | clipboard | type (default auto). On macOS auto means
//                  clipboard: Cmd+V works in every app, terminals included,
//                  while Unicode key events are not honoured by all of them.
//                  type sends the characters themselves and never touches the
//                  clipboard.
//   PASTE_RESTORE_DELAY  seconds before the previous clipboard comes back
//                  (default 1.0) - long enough for a busy app to read it.
//
// Behavior (clipboard):
//   - The previous clipboard is saved with every item and every type, and
//     restored after the paste - but only if the clipboard still holds the
//     dictation, so anything copied in the meantime is never overwritten.
//   - A clipboard marked org.nspasteboard.ConcealedType or TransientType (a
//     password manager's convention) is never read or re-offered; the
//     dictation then stays on the clipboard, as on Linux.
//   - The dictation itself is marked TransientType and AutoGeneratedType, so
//     clipboard managers that follow nspasteboard.org leave it out of their
//     history, and written current-host-only, so Universal Clipboard does not
//     hand it to the user's other devices.
//   - Without Accessibility permission no keystroke can be sent. The text is
//     then left on the clipboard for a manual Cmd+V, and the exit code says so.
//   - With Secure Input active (a password field, or Terminal's Secure
//     Keyboard Entry) the keystroke may be swallowed, so the dictation is left
//     on the clipboard instead of being restored away.
//   - The paste chord is Cmd plus whichever key gives "v" with Cmd held in the
//     current keyboard layout (Dvorak, Workman, "Dvorak - QWERTY Cmd" all
//     differ); the ANSI V position is the fallback.
//   - Pastes are serialized through a lock in the run directory, so a second
//     dictation inside the restore window cannot mistake the first one for
//     the user's clipboard and lose the real one.
//
// Exit codes:
//   0  Pasted (or typed)
//   1  Nothing to paste, or the clipboard could not be written
//   2  No Accessibility permission: the text is on the clipboard, not pasted

import AppKit
import Carbon.HIToolbox

setvbuf(stderr, nil, _IONBF, 0)

func note(_ message: String) {
    FileHandle.standardError.write(Data("sayit-paste: \(message)\n".utf8))
}

let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

if CommandLine.arguments.dropFirst().first == "--check" {
    print("accessibility=\(AXIsProcessTrusted() ? "yes" : "no")")
    print("secure_input=\(IsSecureEventInputEnabled() ? "on" : "off")")
    exit(0)
}

let text = String(decoding: FileHandle.standardInput.readDataToEndOfFile(), as: UTF8.self)
guard !text.isEmpty else { note("no text on stdin"); exit(1) }

let env = ProcessInfo.processInfo.environment
let method = (env["INJECT_METHOD"] ?? "auto").lowercased()
let restoreDelay = Double(env["PASTE_RESTORE_DELAY"] ?? "") ?? 1.0
let trusted = AXIsProcessTrusted()
let source = CGEventSource(stateID: .hidSystemState)
/// Stamped on every event posted here, so Sayit's trigger can tell sayit's own
/// keystrokes from the user's (Trigger.swift has the same constant).
let signature: Int64 = 0x5341_5949_54   // "SAYIT"

// MARK: - Typing

/// Unicode key events, at most 20 UTF-16 units each (the documented limit),
/// never splitting a surrogate pair across two events.
func typeText(_ text: String) {
    var units = Array(text.utf16)
    while !units.isEmpty {
        var n = min(20, units.count)
        if n < units.count, UTF16.isLeadSurrogate(units[n - 1]) { n -= 1 }
        let chunk = Array(units.prefix(n))
        units.removeFirst(n)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down) else { continue }
            event.flags = []
            event.setIntegerValueField(.eventSourceUserData, value: signature)
            chunk.withUnsafeBufferPointer { event.keyboardSetUnicodeString(stringLength: n, unicodeString: $0.baseAddress) }
            event.post(tap: .cghidEventTap)
        }
        usleep(2000)
    }
}

if method == "type" {
    guard trusted else {
        note("Accessibility permission missing - cannot type; nothing was sent")
        exit(2)
    }
    typeText(text)
    exit(0)
}

// MARK: - Clipboard

/// The key that types "v" while Cmd is held, in the current layout.
func pasteKeyCode() -> CGKeyCode {
    let fallback = CGKeyCode(kVK_ANSI_V)
    guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
          let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return fallback }
    let layoutData = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
    let cmd = UInt32((cmdKey >> 8) & 0xFF)
    return layoutData.withUnsafeBytes { buf -> CGKeyCode in
        guard let layout = buf.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return fallback }
        // The ANSI position first: on QWERTY-like layouts it is the answer.
        for code in [UInt16(kVK_ANSI_V)] + (0..<128).map(UInt16.init) {
            var dead: UInt32 = 0
            var length = 0
            var chars = [UniChar](repeating: 0, count: 4)
            let status = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), cmd, UInt32(LMGetKbdType()),
                                        OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, chars.count, &length, &chars)
            if status == noErr, length == 1, chars[0] == UniChar(UInt8(ascii: "v")) { return CGKeyCode(code) }
        }
        return fallback
    }
}

/// Held until this process exits: the next paste waits for our restore.
func serialize() {
    var dir = env["XDG_RUNTIME_DIR"] ?? ""
    if dir.isEmpty {
        var buf = [CChar](repeating: 0, count: Int(PATH_MAX))
        if confstr(_CS_DARWIN_USER_TEMP_DIR, &buf, buf.count) > 0 { dir = String(cString: buf) }
    }
    let fd = open((dir.isEmpty ? "/tmp" : dir) + "/sayit-paste.lock", O_RDWR | O_CREAT, 0o600)
    if fd >= 0 { _ = flock(fd, LOCK_EX) }
}

serialize()
let board = NSPasteboard.general

/// Every item with every type, or nil when the clipboard must not be kept.
func snapshot() -> [[(NSPasteboard.PasteboardType, Data)]]? {
    let types = board.types ?? []
    if types.contains(concealed) || types.contains(transient) { return nil }
    var total = 0
    var items: [[(NSPasteboard.PasteboardType, Data)]] = []
    for item in board.pasteboardItems ?? [] {
        var entries: [(NSPasteboard.PasteboardType, Data)] = []
        for type in item.types {
            guard let data = item.data(forType: type) else { continue }
            total += data.count
            entries.append((type, data))
        }
        items.append(entries)
    }
    // A clipboard holding a huge image or file set is not worth a round
    // trip through this process; leave the dictation in its place instead.
    return total > 64 << 20 ? nil : items
}

let saved = snapshot()

// Current host only: Universal Clipboard must not carry a dictation to the
// user's other devices.
board.prepareForNewContents(with: .currentHostOnly)
let item = NSPasteboardItem()
item.setString(text, forType: .string)
item.setData(Data(), forType: transient)
item.setData(Data(), forType: autoGenerated)
guard board.writeObjects([item]) else { note("could not write the clipboard"); exit(1) }
let ours = board.changeCount

guard trusted else {
    note("Accessibility permission missing - the text is on the clipboard; press Cmd+V")
    exit(2)
}

let secureInput = IsSecureEventInputEnabled()
// The modifier state is set explicitly on both events, so a key still held
// from the trigger cannot turn the paste into another shortcut.
let vKey = pasteKeyCode()
for down in [true, false] {
    guard let event = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: down) else { continue }
    event.flags = .maskCommand
    event.setIntegerValueField(.eventSourceUserData, value: signature)
    event.post(tap: .cghidEventTap)
}

if secureInput {
    note("Secure Input is active - the text stays on the clipboard in case the paste was blocked")
    exit(0)
}

Thread.sleep(forTimeInterval: restoreDelay)
if board.changeCount == ours, let saved = saved {
    board.clearContents()
    if !saved.isEmpty {
        let items = saved.map { entries -> NSPasteboardItem in
            let restored = NSPasteboardItem()
            for (type, data) in entries { restored.setData(data, forType: type) }
            return restored
        }
        board.writeObjects(items)
    }
}
exit(0)
